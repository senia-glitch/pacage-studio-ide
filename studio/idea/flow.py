def _names(names: list[str]) -> str:
    return (
        "ЕДИНОЕ ПРОСТРАНСТВО ИМЁН участников (только эти имена, точно как написано) — "
        + ("; ".join(names) or "не определено")
        + "."
    )


def asis(ctx: str, scenario: dict, problems_: list[str], names: list[str] | None = None) -> str:
    return f"""ЗАДАЧА: построить диаграмму «как есть».
{_scenario(ctx, scenario)}
{_names(names or [])}
Принятые проблемы сценария: {_list(problems_)}.

Опиши по шагам, как этот сценарий проходит СЕЙЧАС, без автоматизации и только внутри границ системы. Жёсткое правило:
КАЖДАЯ принятая проблема должна быть отмечена ровно на том шаге, где она возникает: у шага поле pain: {{"what": "<название проблемы>"}},
название — ТОЧНО как в списке выше, без изменений. Других значений в pain.what быть не может, шагов без смысла (без реального действия
между двумя разными участниками) тоже.
Ещё два правила. Шаг не может противоречить принятым проблемам: то, что появляется только с автоматизацией (уведомления, статусы,
проверки, автоматические ответы), в «как есть» не показывай — иначе проблема «этого нет» окажется неверной. И проблема отмечается
на том шаге, к действию которого она относится по смыслу, а не на соседнем.
Одна карточка kind="как есть", title="Как есть: <название сценария>", body — главная проблема процесса, одно предложение.
{DIAGRAM_FORMAT}"""


