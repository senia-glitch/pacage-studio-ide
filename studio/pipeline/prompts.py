def line(card: dict, with_body: bool = True) -> str:
    spec = KINDS.get(card["kind"])
    kind = spec.title if spec else card["kind"]
    text = f"{card['id']} [{kind}] {card['title']}"
    attrs = card.get("attrs") or {}
    if attrs.get("answer"):
        text += f" — ответ: {attrs['answer']}"
    if with_body and card.get("body"):
        text += f"\n    {card['body'][:600]}"
    return text


def render(bank: ProjectBank, *kinds: str, status: tuple[str, ...] | None = None) -> str:
    """Записи видов ``kinds`` списком для подсказки. Пусто — «нет»."""
    out = []
    for kind in kinds:
        for card in bank.records(kind):
            if status is None or card["status"] in status:
                out.append(line(card))
    return "\n".join(out) if out else "(нет)"


def constitution(bank: ProjectBank) -> str:
    """«Конституция» проекта: принятое и черновое из границ, ограничений и словаря."""
    items = [c for kind in ("boundary", "constraint", "term", "style") for c in bank.records(kind)]
    out = [line(c, with_body=False) for c in items]
    asked = [c for c in bank.records("question") if (c.get("attrs") or {}).get("source")]
    decided = [c for c in asked if c["attrs"].get("answer")]  # решения по ходу работы: им не противоречим
    out += [f"Решение: {c['title']} — {c['attrs']['answer']}" for c in decided[-30:]]
    return "\n".join(out) or "(пока нет)"
